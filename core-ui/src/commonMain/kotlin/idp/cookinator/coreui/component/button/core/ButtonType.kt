package idp.cookinator.coreui.component.button.core

/**
 * An enum class representing the types of buttons available in the UI.
 *
 * This enum is used to differentiate between different button styles, such as large and small
 * buttons. Each button type can have its own styling and behavior defined in the UI components that
 * utilize this enum.
 */
enum class ButtonType {
    LARGE,
    SMALL,
}
